"""Generate a source-only inventory; never import app.py or read private data."""
from pathlib import Path
from html.parser import HTMLParser
import ast
import re

ROOT = Path(__file__).resolve().parents[1]


def clean(value):
    return re.sub(r"\s+", " ", str(value)).replace("|", "\\|").strip()


class Controls(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.rows = []

    def handle_starttag(self, tag, attrs):
        if tag not in {"button", "input", "select", "textarea", "form", "a", "h1", "h2", "h3"}:
            return
        values = dict(attrs)
        details = "; ".join(f"{key}={values[key]}" for key in
                            ("id", "name", "type", "href", "action", "placeholder", "aria-label", "onclick", "onchange", "required")
                            if key in values)
        self.rows.append((self.getpos()[0], tag, details or "(no identifying attributes)"))


def main():
    lines = ["# Current source inventory", "",
             "Generated by `python tools/map_app_source.py`. Source-only index; no app execution or private data reads.", "",
             "This inventories literal template controls, routes and named JavaScript functions. Dynamic controls created in JavaScript are not parsed as HTML; see the behavior specification and named functions. Jinja branches remain unevaluated.", "",
             "## Flask routes", "",
             "| Source | Methods | Route | Handler |", "| --- | --- | --- | --- |"]
    routes = 0
    for relative in ("app.py", "blueprints/custom_player_routes.py"):
        tree = ast.parse((ROOT / relative).read_text(encoding="utf-8-sig"))
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for decorator in node.decorator_list:
                if not isinstance(decorator, ast.Call) or not isinstance(decorator.func, ast.Attribute) or decorator.func.attr != "route":
                    continue
                route = ast.literal_eval(decorator.args[0])
                methods = next((ast.literal_eval(k.value) for k in decorator.keywords if k.arg == "methods"), ["GET"])
                lines.append(f"| `{relative}:{node.lineno}` | {', '.join(methods)} | `{route}` | `{node.name}` |")
                routes += 1
    lines += ["", "## Missing literal render targets", ""]
    missing = []
    for relative in ("app.py", "blueprints/custom_player_routes.py"):
        tree = ast.parse((ROOT / relative).read_text(encoding="utf-8-sig"))
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "render_template" and node.args:
                target = node.args[0]
                if isinstance(target, ast.Constant) and isinstance(target.value, str) and not (ROOT / "templates" / target.value).exists():
                    missing.append(f"- `{relative}:{node.lineno}` -> `{target.value}`")
                elif isinstance(target, ast.JoinedStr):
                    missing.append(f"- `{relative}:{node.lineno}` -> dynamic template `{ast.unparse(target)}`; verify generated targets separately.")
    lines += missing or ["None."]
    count = 0
    for path in sorted((ROOT / "templates").glob("*.html")):
        parser = Controls()
        parser.feed(path.read_text(encoding="utf-8-sig"))
        relative = path.relative_to(ROOT).as_posix()
        lines += ["", f"## {relative}", "", "| Line | Element | Attributes |", "| --- | --- | --- |"]
        for line, tag, attributes in parser.rows:
            lines.append(f"| {line} | `{tag}` | {clean(attributes)} |")
            count += 1
    lines += ["", "## JavaScript named functions", "", "| Source | Function |", "| --- | --- |"]
    paths = list((ROOT / "templates").glob("*.html")) + list((ROOT / "static/js").glob("*.js")) + [ROOT / "main.js", ROOT / "preload.js"]
    for path in sorted(paths):
        for number, line in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
            match = re.search(r"\b(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\(", line)
            if match:
                lines.append(f"| `{path.relative_to(ROOT).as_posix()}:{number}` | `{match.group(1)}` |")
    destination = ROOT / "docs/current-source-inventory.md"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {destination.name}: {routes} routes, {count} literal template controls.")


if __name__ == "__main__":
    main()
