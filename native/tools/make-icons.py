"""Renders the UI icons from the Phosphor icon font (MIT). Development tool; needs Pillow.

Usage: python tools/make-icons.py <unpacked @phosphor-icons/web 2.1.1 package folder>

Each icon is rendered by FreeType at the exact pixel size of every display scale, so
neither platform resamples it at run time. Two sets: 24 points (regular weight) for
ordinary controls, and 16 points (bold weight) where icons sit small beside text.
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/assets/icons"
SCALES = (1, 1.5, 2, 3, 4)  # Android accepts only these density buckets.

# App name -> Phosphor name (and weight override).
ICONS = {
    "back": "caret-left",
    "forward": "caret-right",
    "up": "caret-up",
    "down": "caret-down",
    "edit": "pencil-simple",
    "top": "arrow-up",
    "alert": "warning",
    "pause": "pause",
    "fullscreen": "corners-out",
    "volume": "speaker-high",
    "mute": "speaker-slash",
    "captions": "closed-captioning",
    "home": "house",
    "play": "play",
    "queue": "queue",
    "search": "magnifying-glass",
    "filter": "funnel",
    "settings": "gear-six",
    "plus": "plus",
    "check": "check",
    "close": "x",
    "bookmark": "bookmark-simple",
    "bookmarkFilled": ("bookmark-simple", "fill"),
    "trash": "trash",
    "grid": "squares-four",
    "list": "list",
    "tag": "tag",
    "link": "link",
    "reset": "arrow-counter-clockwise",
    "folder": "folder",
    "player": "monitor-play",
    "more": "dots-three",
}


def codepoints(package: Path, weight: str) -> dict:
    folder = "regular" if weight == "regular" else weight
    css = (package / "src" / folder / "style.css").read_text(encoding="utf-8")
    suffix = "" if weight == "regular" else f"-{weight}"
    pattern = re.compile(r"\.ph" + re.escape(suffix) + r"\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*\"\\([0-9a-f]+)\"")
    return {name: int(code, 16) for name, code in pattern.findall(css)}


def font_path(package: Path, weight: str) -> Path:
    name = "Phosphor.ttf" if weight == "regular" else f"Phosphor-{weight.capitalize()}.ttf"
    return package / "src" / weight / name


def render(font_file: Path, code: int, px: int) -> Image.Image:
    # The glyphs are drawn on the font's em square, which is the icon's box.
    font = ImageFont.truetype(str(font_file), px)
    image = Image.new("L", (px, px), 0)
    ascent, _ = font.getmetrics()
    ImageDraw.Draw(image).text((0, ascent), chr(code), font=font, fill=255, anchor="ls")
    white = Image.new("RGBA", (px, px), (255, 255, 255, 0))
    white.putalpha(image)
    return white


def main(package: str) -> None:
    package = Path(package)
    maps = {w: codepoints(package, w) for w in ("regular", "bold", "fill")}
    for stale in OUT.glob("*.webp"):
        stale.unlink()
    for app_name, spec in ICONS.items():
        name, weight = (spec, None) if isinstance(spec, str) else spec
        for base, default_weight, tag in ((24, "regular", ""), (16, "bold", "-sm")):
            w = weight or default_weight
            code = maps[w][name]
            for scale in SCALES:
                px = round(base * scale)
                suffix = "" if scale == 1 else f"@{scale:g}x"
                render(font_path(package, w), code, px).save(OUT / f"{app_name}{tag}{suffix}.webp", lossless=True, quality=100, method=6)
    lines = ["// Generated by tools/make-icons.py from Phosphor Icons (MIT). Do not edit.", "export const regular = {"]
    lines += [f"  {n}: require('../assets/icons/{n}.webp')," for n in ICONS]
    lines += ["} as const;", "export const small = {"]
    lines += [f"  {n}: require('../assets/icons/{n}-sm.webp')," for n in ICONS]
    lines += ["} as const;", ""]
    (ROOT / "src/components/iconAssets.ts").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(ICONS)} icons written")


if __name__ == "__main__":
    main(sys.argv[1])
